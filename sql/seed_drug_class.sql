-- sql/seed_drug_class.sql — 一般名 -> 薬効クラス
--
-- 実データの gnrc_name（CY2022-2024 の geo_drug、2109 種）から語幹一致で生成。
-- 手で薬剤名を並べないこと。CMS の一般名は列幅の都合で切り詰められており
-- （DAPAGLIFLOZ PROPANED/METFORMIN、EMPAGLIFLOZ/LINAGLIP/METFORMIN）、
-- 教科書どおりの名前を IN で並べると取りこぼす。
--
-- 語幹一致の落とし穴（実際に踏んだもの）:
--   'STATIN'  -> IMIPENEM/CILASTATIN SODIUM（抗菌薬）が混入する
--   'PRAZOLE' -> ARIPIPRAZOLE / BREXPIPRAZOLE（抗精神病薬）が混入する
--   いずれも語幹を薬剤名まで具体化して回避している。
--
-- 配合剤は成分ごとに複数クラスに属する（例 EMPAGLIFLOZIN/METFORMIN HCL は
-- SGLT2 と BIGUANIDE の両方）。クラス横断で合計すると二重計上になるので、
-- 集計は必ず 1 クラスに絞ること。
--
-- 結合キーは gnrc_name_norm（UPPER 正規化列）。
--
--   bq query --use_legacy_sql=false < sql/seed_drug_class.sql

